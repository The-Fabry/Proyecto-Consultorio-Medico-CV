    // CONSTRUCTOR CON PARÁMETROS Y ZXING (CÓDIGO DE BARRAS REAL)
    public TicketDigita(String paciente, String medico, String fecha, String codigoBarras) {
        initComponents();
        this.setLocationRelativeTo(null); // Centrar la ventana

        // Asignar los datos a tus etiquetas del diseño
        jlblPaciente.setText("Paciente: " + paciente);
        jlblMedico.setText("Médico: " + medico);
        jlblFecha.setText("Fecha: " + fecha);

        // Configurar el panel para que tenga buen tamaño
        jpnlCodigoBarras.setLayout(new BorderLayout());
        jpnlCodigoBarras.setPreferredSize(new Dimension(300, 80));
        jpnlCodigoBarras.removeAll();

        try {
            // Generar la matriz del código de barras (Código 128) usando ZXing
            int width = 280;
            int height = 55;
            BitMatrix bitMatrix = new MultiFormatWriter().encode(
                codigoBarras, 
                BarcodeFormat.CODE_128, 
                width, 
                height
            );

            // Convertir la matriz de bits en una imagen BufferedImage
            BufferedImage barcodeImage = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
            for (int x = 0; x < width; x++) {
                for (int y = 0; y < height; y++) {
                    barcodeImage.setRGB(x, y, bitMatrix.get(x, y) ? Color.BLACK.getRGB() : Color.WHITE.getRGB());
                }
            }

            // Crear un panel personalizado para mostrar la imagen del código de barras y el texto debajo
            JPanel panelBarras = new JPanel() {
                @Override
                protected void paintComponent(Graphics g) {
                    super.paintComponent(g);
                    // Fondo blanco
                    g.setColor(Color.WHITE);
                    g.fillRect(0, 0, getWidth(), getHeight());

                    // Dibujar la imagen del código de barras centrada
                    int imgX = (getWidth() - width) / 2;
                    g.drawImage(barcodeImage, imgX, 5, this);

                    // Dibujar el texto legible debajo del código de barras
                    g.setFont(new Font("Monospaced", Font.BOLD, 12));
                    g.setColor(Color.BLACK);
                    FontMetrics fm = g.getFontMetrics();
                    int textWidth = fm.stringWidth(codigoBarras);
                    int textX = (getWidth() - textWidth) / 2;
                    g.drawString(codigoBarras, textX, height + 18);
                }
            };

            jpnlCodigoBarras.add(panelBarras, BorderLayout.CENTER);

        } catch (Exception e) {
            // Si ocurre algún error, mostramos respaldo en texto plano
            JLabel lblFallback = new JLabel(codigoBarras, SwingConstants.CENTER);
            lblFallback.setFont(new Font("Monospaced", Font.BOLD, 16));
            jpnlCodigoBarras.add(lblFallback, BorderLayout.CENTER);
            e.printStackTrace();
        }

        jpnlCodigoBarras.revalidate();
        jpnlCodigoBarras.repaint();
    }

