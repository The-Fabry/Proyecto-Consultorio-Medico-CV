    private void cargarEspecialistas() {
        CitaDAO dao = new CitaDAO();
        List<Especialista> lista = dao.listarEspecialistas();

        jcbxEspecialista.removeAllItems();
        for (Especialista esp : lista) {
            // Agregamos como texto combinando el nombre y la especialidad
            jcbxEspecialista.addItem(esp.getNombreCompleto() + " - " + esp.getEspecialidad());
        }
    }

    // MÉTODO PRIVADO PARA LA LÓGICA DE GUARDADO
    private void guardarCitaRegistrada() {
        String cedula = jtxtCedula.getText().trim();
        String nombre = jtxtNombre.getText().trim();
        String telefono = jtxtTelefono.getText().trim();
        String fechaHora = jtxtFecha.getText().trim();

        // 1. Validación de campos vacíos
        if (cedula.isEmpty() || nombre.isEmpty() || telefono.isEmpty() || fechaHora.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Obtener el texto del médico seleccionado en el ComboBox
        String medicoSeleccionado = (String) jcbxEspecialista.getSelectedItem();
        if (medicoSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un especialista.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 3. Generar un código de barras único para el ticket
        String codigoBarras = "CIT-" + cedula + "-" + (System.currentTimeMillis() % 10000);

        // 4. Guardar en la BD mediante el DAO (aquí por defecto mandamos el ID 1 o el que corresponda al médico)
        CitaDAO dao = new CitaDAO();
        boolean exito = dao.guardarCita(cedula, nombre, "Sin Apellido", telefono, 1, fechaHora, codigoBarras);

        if (exito) {
        JOptionPane.showMessageDialog(this, "¡Cita agendada con éxito!\nCódigo de ticket: " + codigoBarras, "Éxito", JOptionPane.INFORMATION_MESSAGE);
        
        // Abrir el Ticket Digital pasándole los datos
        TicketDigita ticket = new TicketDigita(nombre, medicoSeleccionado, fechaHora, codigoBarras);
        ticket.setVisible(true);
        
        this.dispose(); // Cierra la ventana de agendamiento
    }
    }

